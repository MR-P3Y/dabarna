// Generated English assets share all state transitions, requests and permissions
// with the Persian source. Only source-owned presentation literals are translated.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const acorn=await import(process.env.ACORN_MODULE || 'acorn');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../backend/app/static/mini');
const dictionary=JSON.parse(fs.readFileSync(path.join(root,'locales/en.json'),'utf8'));
const escape=s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const keys=Object.keys(dictionary).filter(k=>/[\u0621-\u064a\u067e\u0686\u0698\u06a9\u06af\u06cc]/.test(k)).sort((a,b)=>b.length-a.length);
const matcher=new RegExp(keys.map(escape).join('|'),'g');
const translate=s=>s.replace(matcher,k=>dictionary[k]);
function compile(s){
 const tree=acorn.parse(s,{ecmaVersion:'latest',sourceType:'module'}),edits=[];
 function walk(n,parent,key){
  if(!n||typeof n!=='object')return;
  if(n.type==='Literal'&&typeof n.value==='string'){
   const propertyKey=parent?.type==='Property'&&key==='key'&&!parent.computed;
   const predicate=parent?.type==='CallExpression'&&['includes','startsWith','endsWith','indexOf','replace','replaceAll','match','split'].includes(parent.callee?.property?.name)&&key==='arguments';
   if(!propertyKey&&!predicate){const t=translate(n.value);if(t!==n.value)edits.push([n.start,n.end,JSON.stringify(t)]);}
  }
  if(n.type==='TemplateElement'&&n.value.cooked!=null){const t=translate(n.value.cooked);if(t!==n.value.cooked)edits.push([n.start,n.end,t.replace(/\\/g,'\\\\').replace(/`/g,'\\`').replace(/\$\{/g,'\\${')]);}
  for(const [k,v]of Object.entries(n)){if(k==='raw')continue;if(Array.isArray(v))v.forEach(x=>walk(x,n,k));else if(v&&typeof v==='object')walk(v,n,k);}
 }
 walk(tree);
 for(const [a,b,t]of edits.sort((a,b)=>b[0]-a[0]))s=s.slice(0,a)+t+s.slice(b);
 return s.replaceAll('"fa-IR"','"en-GB"').replaceAll('calendar: "persian"','calendar: "gregory"').replaceAll('numberingSystem: "arabext"','numberingSystem: "latn"');
}
const outputs=new Map();
outputs.set('locale-en.mjs','// Generated exact translations for server-owned UI labels; never use on user content.\nexport const knownText = value => dictionary[String(value ?? "")] ?? String(value ?? "");\nconst dictionary = '+JSON.stringify(dictionary)+';\n');
for(const file of ['app.js','experience.mjs','tracking.mjs','automation-clocks.mjs']){
 let text=compile(fs.readFileSync(path.join(root,file),'utf8'));
 for(const module of ['experience','tracking','automation-clocks'])text=text.replaceAll('./'+module+'.mjs?','./'+module+'.en.mjs?');
 if(file==='app.js'){
  text='import {knownText} from "./locale-en.mjs?v=20261124";\n'+text;
  text=text.replaceAll('safeText(item.title ||', 'safeText(knownText(item.title) ||').replaceAll('safeText(item.body || "")', 'safeText(notificationBody(item))').replaceAll('receipt?.title ||', 'knownText(receipt?.title) ||').replaceAll('safeText(item?.label ||', 'safeText(knownText(item?.label) ||');
  text='import {notificationBody} from "./server-labels.en.mjs?v=20261124";\n'+text;
  text=text.replace('const raw = String(detail || "").trim();','const raw = knownText(String(detail || "").trim());');
  text=text.replace(/function toFaDigits\(value\) \{[\s\S]*?\n\}/,'function toFaDigits(value) { return String(value ?? ""); }');
 }
 if(file==='experience.mjs') text=text.replace('.includes("ناسازگار")', '.includes("inconsistent")');
 if(file==='tracking.mjs'){
  text='import {knownText} from "./locale-en.mjs?v=20261124";\n'+text;
  text='import {fieldValue} from "./server-labels.en.mjs?v=20261124";\n'+text;
  text=text.replaceAll('escape(f.value)', 'escape(fieldValue(f))');
  text=text.replace('dialog.dir = "rtl"','dialog.dir = "ltr"');
  text=text.replaceAll('escape(row.title)','escape(kinds[row.kind] || knownText(row.title))').replaceAll('escape(row.status_label)','escape(statuses[row.status] || knownText(row.status_label))').replaceAll('escape(f.label)','escape(knownText(f.label))').replaceAll('escape(t.label)','escape(knownText(t.label))').replaceAll('escape(w.label)','escape(knownText(w.label))');
 }
 acorn.parse(text,{ecmaVersion:'latest',sourceType:'module'});
 outputs.set(file.replace(/\.(m?js)$/,'.en.$1'),'// Generated by dev/tools/build-mini-locales.mjs; edit Persian source and locales/en.json.\n'+text);
}
let html=fs.readFileSync(path.join(root,'index.html'),'utf8');
html=html.replace(/>([^<>]+)</g,(all,t)=>'>'+translate(t)+'<').replace(/(aria-label|title|placeholder)="([^"]*)"/g,(all,k,v)=>k+'="'+translate(v)+'"').replace('lang="fa" dir="rtl"','lang="en" dir="ltr"').replace('src="./app.js?','src="./app.en.js?');
outputs.set('en.html',html);
let drift=false;
for(const [name,text] of outputs){const full=path.join(root,name);if(process.argv.includes('--check')){if(!fs.existsSync(full)||fs.readFileSync(full,'utf8')!==text){console.error('Stale locale asset:',name);drift=true;}}else fs.writeFileSync(full,text);}
if(drift)process.exitCode=1;else console.log('PASS: '+outputs.size+' English assets generated from one source; '+Object.keys(dictionary).length+' catalog entries');
